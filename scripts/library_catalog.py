"""Shared local-library metadata writers. No network access during application startup."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'data' / 'library-sources.json'


def write_packs(manifest):
    fields = ['id', 'label', 'group', 'section', 'file', 'kind', 'description', 'referenceTitle', 'referenceUrl', 'coverage']
    packs = [{**{k: p[k] for k in fields if k in p},'revision':p['sha256'][:16]} for p in manifest['collections'] if p['games']]
    (ROOT / 'extra-collections.js').write_text('// Generated by the explicit scripts/enrich_*.py maintenance commands.\nexport const EXTRA_SCORE_PACKS = ' + json.dumps(packs, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')


def write_catalog(manifest):
    kinds = {'game': '完整主线', 'line': '示范片段', 'study': '残局研究', 'fragment': '实战残局片段', 'course': '教材示例与范局', 'puzzle': '分级练习'}
    lines = ['# 本地增补棋谱来源', '',
             f"增补目录共 {len(manifest['collections'])} 个合集、{manifest['totalNewEntries']:,} 条内容。条目包含完整实战、教材示例、残局续篇和练习；不同专题与棋手合集允许交叉，不应视作互不重复的比赛数。", '',
             '棋谱主线经过合法性检查，保留事实性标签与来源，不打包现代书籍讲解。练习题保留原始编号、主题、等级分和参考线，等级分来自题库，不代表对用户水平的评测。', '',
             '| 合集 | 类型 | 条目数 | 来源 |', '| --- | --- | ---: | --- |']
    for pack in manifest['collections']:
        urls = [s['url'] for s in pack.get('sources', [])] or ([pack['source']] if pack.get('source') else [])
        links = '、'.join(f'[谱源 {i+1}]({url})' for i, url in enumerate(urls)) if urls else '由已注明来源的本地实战截取，赛事与起始局面保留在 PGN 标签中'
        lines.append(f"| {pack['label']} | {kinds.get(pack['kind'],pack['kind'])} | {pack['games']} | {links} |")
    lines.extend(['', '课程顺序、覆盖范围及练习方式见 [CURRICULUM.md](CURRICULUM.md)。各文件与上游下载校验值见 [library-sources.json](library-sources.json)。', '',
                  '维护采集：`python scripts/enrich_library.py`、`python scripts/enrich_openings.py`、`python scripts/enrich_champions.py`、`python scripts/enrich_training.py`。只在维护时联网，日常阅读和分析使用本地文件与本机 Stockfish。', ''])
    (ROOT / 'data' / 'LIBRARY_SOURCES.md').write_text('\n'.join(lines), encoding='utf-8')


def commit_collections(additions, section, metadata=None):
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    ids = {p['id'] for p in additions}
    manifest['collections'] = [p for p in manifest['collections'] if p['id'] not in ids] + additions
    manifest['totalNewEntries'] = sum(p['games'] for p in manifest['collections'])
    manifest[section + 'UpdatedAt'] = datetime.now(timezone.utc).isoformat()
    manifest[section + 'AdditionCount'] = sum(p['games'] for p in additions)
    if metadata:
        manifest[section + 'Quality'] = metadata
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    write_packs(manifest)
    write_catalog(manifest)
    return manifest


def save_collection(ident, games, **metadata):
    from enrich_library import export_games
    content = export_games(games).encode('utf-8')
    (ROOT / 'data' / 'complete' / (ident + '.pgn')).write_bytes(content)
    return {'id': ident, 'file': ident + '.pgn', 'games': len(games), 'sha256': hashlib.sha256(content).hexdigest(), **metadata}
